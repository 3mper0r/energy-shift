"use client";

import { AlertTriangle, BookOpen, Check, Copy, Lightbulb, Sparkles, TrendingUp } from "lucide-react";
import { useEffect, useState } from "react";
import type { Insight, InsightSeverity } from "@/lib/insights";
import type { ScenarioInput, ScenarioResult } from "@/lib/scenario";
import { Button, Card, CardHeader } from "./ui";

const ICONS: Record<InsightSeverity, { icon: typeof AlertTriangle; className: string; label: string }> = {
  alert: { icon: AlertTriangle, className: "text-alert", label: "Risk" },
  insight: { icon: Lightbulb, className: "text-warn", label: "Insight" },
  opportunity: { icon: TrendingUp, className: "text-ok", label: "Opportunity" },
};

export function InsightsPanel({
  result,
  insights,
  onApply,
}: {
  result: ScenarioResult;
  insights: Insight[];
  onApply: (patch: Partial<ScenarioInput>) => void;
}) {
  const action = insights.find((i) => i.action)?.action;
  const score = result.summary.transitionScore;
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    if (!copied) return;
    const id = window.setTimeout(() => setCopied(false), 2000);
    return () => window.clearTimeout(id);
  }, [copied]);

  const copyInsights = async () => {
    const text = insights.map((i) => `${i.title}: ${i.body}`).join("\n");
    await navigator.clipboard.writeText(text);
    setCopied(true);
  };

  return (
    <Card id="insights" labelledBy="insights-title" className="flex flex-col">
      <CardHeader
        id="insights-title"
        title="Strategic insights"
        info="Generated by deterministic rules from the current scenario (no external AI). Risks are listed first. The suggested adjustment applies the first actionable recommendation to the controls."
      />
      <ul className="flex flex-col gap-3" aria-live="polite">
        {insights.map((insight) => {
          const meta = ICONS[insight.severity];
          const Icon = meta.icon;
          return (
            <li key={insight.id}>
              <p className="flex items-center gap-1.5 text-[12px] font-medium">
                <Icon className={`size-3.5 shrink-0 ${meta.className}`} aria-hidden />
                <span className="sr-only">{meta.label}: </span>
                {insight.title}
              </p>
              <p className="mt-0.5 text-[11.5px] leading-snug text-muted">{insight.body}</p>
            </li>
          );
        })}
      </ul>

      <div className="mt-auto pt-4">
        <div className="mb-1.5 flex justify-between text-[11.5px] text-muted">
          <span id="score-label">Transition score</span>
          <span className="tabular-nums">{score}/100</span>
        </div>
        <div className="flex items-center gap-2.5">
          <div
            className="h-3 flex-1 overflow-hidden rounded-[3px] bg-track"
            role="progressbar"
            aria-labelledby="score-label"
            aria-valuemin={0}
            aria-valuemax={100}
            aria-valuenow={score}
          >
            <div className="h-full rounded-[3px] bg-ok transition-[width] duration-300" style={{ width: `${score}%` }} />
          </div>
          <span className="text-[11px] font-medium">{result.summary.status}</span>
        </div>
      </div>

      <div className="mt-4 grid grid-cols-2 gap-2">
        {action ? (
          <Button onClick={() => onApply(action.patch)} title={action.label} aria-label={`Apply recommendation: ${action.label}`}>
            <Sparkles className="size-3.5" aria-hidden />
            <span className="truncate">Apply recommendation</span>
          </Button>
        ) : (
          <Button onClick={copyInsights}>
            {copied ? <Check className="size-3.5 text-ok" aria-hidden /> : <Copy className="size-3.5" aria-hidden />}
            <span aria-live="polite">{copied ? "Copied" : "Copy insights"}</span>
          </Button>
        )}
        <a
          href="#methodology"
          className="inline-flex h-9 items-center justify-center gap-2 rounded-[9px] bg-navy px-3 text-[12.5px] font-medium text-white transition-colors hover:bg-navy-hover focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-royal-2"
        >
          <BookOpen className="size-3.5" aria-hidden />
          Methodology
        </a>
      </div>
      {action ? <p className="mt-1.5 text-[10.5px] text-subtle">Suggested: {action.label}</p> : null}
    </Card>
  );
}
